// Downloads each enemy's picture from the Hypixel SkyBlock Wiki into public/mobs/, and writes
// src/data/mobSprites.js mapping enemy names to them. The wiki's full-body render ("<Mob>.png", fetched
// as a 512 px tall thumbnail; animated GIFs included) where there is one, else its head sprite ("<Mob> Sprite.png"). The images
// are the wiki's, under CC BY-NC-SA 3.0 (credited in the README). Run: node scripts/mob-sprites.mjs
import fs from 'fs';
import { ENEMIES } from '../src/data/mechanics.js';

const API = 'https://hypixelskyblock.minecraft.wiki/api.php';
const OUT_DIR = new URL('../public/mobs/', import.meta.url);
const OUT_MAP = new URL('../src/data/mobSprites.js', import.meta.url);
// Tall enough to stay sharp on high-density screens; only one picture is loaded per simulation.
const RENDER_HEIGHT = 512;

// An enemy's wiki name: without its tier ("Voidgloom Seraph IV") or a note in brackets ("Enderman (Lv45)").
const spriteName = (name) => name.replace(/ \([^)]*\)$/, '').replace(/ (I|II|III|IV|V)$/, '').trim();
// Also the targets that appear during fights (demons, pups).
const names = [...new Set([...ENEMIES.map((e) => spriteName(e.name)), 'Quazii', 'Typhoeus', 'Sven Pup'])];

// The image URL for each name's wiki file (following the wiki's redirects), or nothing.
async function lookup(fileOf, extra = '') {
  const urls = {};
  for (let i = 0; i < names.length; i += 50) {
    const batch = names.slice(i, i + 50);
    const titles = batch.map((n) => `File:${fileOf(n)}`).join('|');
    const j = await (await fetch(`${API}?action=query&titles=${encodeURIComponent(titles)}&prop=imageinfo&iiprop=url${extra}&format=json&formatversion=2&redirects=1`)).json();
    const norm = Object.fromEntries((j.query.normalized || []).map((r) => [r.from, r.to]));
    const redir = Object.fromEntries((j.query.redirects || []).map((r) => [r.from, r.to]));
    const info = Object.fromEntries(j.query.pages.filter((p) => p.imageinfo).map((p) => [p.title, p.imageinfo[0]]));
    for (const n of batch) {
      let t = `File:${fileOf(n)}`;
      t = norm[t] || t;
      t = redir[t] || t;
      if (info[t]) urls[n] = info[t].thumburl || info[t].url;
    }
  }
  return urls;
}

const renders = await lookup((n) => `${n}.png`, `&iiurlheight=${RENDER_HEIGHT}`);
const heads = await lookup((n) => `${n} Sprite.png`);

// Start from an empty folder (emptied rather than removed, which Windows refuses while it's open).
fs.mkdirSync(OUT_DIR, { recursive: true });
for (const f of fs.readdirSync(OUT_DIR)) fs.rmSync(new URL(f, OUT_DIR));
const map = {};
const saved = new Map(); // image URL -> file name, so shared images are stored once
for (const n of names) {
  const render = renders[n];
  const url = render || heads[n];
  if (!url) continue;
  let file = saved.get(url);
  if (!file) {
    file = decodeURIComponent(url.split('?')[0].split('/').pop()).replace(/^\d+px-/, '').replace(/[^\w.-]+/g, '_');
    const res = await fetch(url);
    fs.writeFileSync(new URL(file, OUT_DIR), Buffer.from(await res.arrayBuffer()));
    saved.set(url, file);
  }
  map[n] = render ? `mobs/${file}` : `mobs/${file}#head`;
}

fs.writeFileSync(OUT_MAP, `// Generated by scripts/mob-sprites.mjs on ${new Date().toISOString().slice(0, 10)}: enemy name -> picture in
// public/mobs/, from the Hypixel SkyBlock Wiki (CC BY-NC-SA 3.0): its full-body render, or its head
// sprite (marked #head) when it has no render. Don't edit by hand: re-run the script.
export const MOB_SPRITES = ${JSON.stringify(Object.fromEntries(Object.entries(map).sort()), null, 1)};

// The picture for an enemy (tier and bracketed notes are ignored): { src, head } or undefined.
export function mobSprite(name) {
  const path = MOB_SPRITES[(name || '').replace(/ \\([^)]*\\)$/, '').replace(/ (I|II|III|IV|V)$/, '').trim()];
  return path ? { src: path.replace(/#head$/, ''), head: path.endsWith('#head') } : undefined;
}
`);
const n = Object.values(map);
console.log(`${n.filter((p) => !p.endsWith('#head')).length} renders, ${n.filter((p) => p.endsWith('#head')).length} head sprites, ${names.length - n.length} without; ${saved.size} images saved`);
