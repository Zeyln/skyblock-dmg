// Generates src/data/reforgeStones.js from the NotEnoughUpdates repo's reforge stone list: which item
// types (or items) each stone reforge fits, and its combat stats per rarity. Run: node scripts/reforge-stones.mjs
import fs from 'fs';

const NEU = 'https://raw.githubusercontent.com/NotEnoughUpdates/NotEnoughUpdates-REPO/master/constants/reforgestones.json';
const ITEMS = 'https://api.hypixel.net/v2/resources/skyblock/items';
const OUT = new URL('../src/data/reforgeStones.js', import.meta.url);

const RARITIES = ['COMMON', 'UNCOMMON', 'RARE', 'EPIC', 'LEGENDARY', 'MYTHIC', 'DIVINE'];
// NEU stat names -> the calculator's; other stats (mining, farming, fishing...) don't affect a hit.
const STATS = {
  damage: 'DAMAGE', strength: 'STRENGTH', crit_chance: 'CRITICAL_CHANCE', crit_damage: 'CRITICAL_DAMAGE',
  ferocity: 'FEROCITY', attack_speed: 'ATTACK_SPEED', speed: 'WALK_SPEED', health: 'HEALTH', defense: 'DEFENSE',
};
// Item types that matter for combat (pickaxes, farming tools, vacuums, nets and spades are left out).
const TYPES = ['SWORD', 'SWORD/ROD', 'BOW', 'ROD', 'AXE', 'ARMOR', 'HELMET', 'CHESTPLATE', 'LEGGINGS', 'BOOTS',
  'EQUIPMENT', 'NECKLACE', 'CLOAK', 'BELT', 'GLOVES', 'BRACELET'];

const [stones, items] = await Promise.all([fetch(NEU).then((r) => r.json()), fetch(ITEMS).then((r) => r.json())]);
const names = Object.fromEntries(items.items.map((i) => [i.id, i.name]));

const out = {};
for (const [stoneId, s] of Object.entries(stones)) {
  const forItems = typeof s.itemTypes === 'object' ? s.itemTypes.internalName : null;
  const types = typeof s.itemTypes === 'string' ? s.itemTypes.split(',').map((t) => t.trim()) : [];
  if (!forItems && !types.some((t) => TYPES.includes(t))) continue;
  // Stats per rarity, Common → Divine; a rarity the stone can't be used at repeats the one below it.
  const stats = {};
  let last = {};
  for (const r of RARITIES) {
    const row = s.reforgeStats?.[r];
    if (row) last = row;
    for (const [k, key] of Object.entries(STATS)) (stats[key] ??= []).push(last[k] || 0);
  }
  for (const k of Object.keys(stats)) if (stats[k].every((v) => !v)) delete stats[k];
  const key = s.reforgeName.toLowerCase().replace(/[^a-z]/g, '');
  out[key] = {
    name: s.reforgeName,
    stone: names[stoneId] || stoneId,
    ...(forItems ? { items: forItems } : { types }),
    stats,
    ...(s.reforgeAbility ? { ability: s.reforgeAbility.replace(/§./g, '') } : {}),
  };
}

const body = `// Generated by scripts/reforge-stones.mjs from the NotEnoughUpdates repo (constants/reforgestones.json)
// on ${new Date().toISOString().slice(0, 10)}. Don't edit by hand: re-run the script.
// Each stone reforge: the item types it fits (or the only items it fits), and stats per rarity, Common → Divine.
export const REFORGE_STONES = ${JSON.stringify(Object.fromEntries(Object.entries(out).sort()), null, 1)};
`;
fs.writeFileSync(OUT, body);
console.log(`${Object.keys(out).length} stone reforges written to src/data/reforgeStones.js`);
